"""Fidel server.

Phase 1: a health check, plus static files:
  /embed/          the built player (fidel.js, fidel.css)
  /demo/           demo pages, e.g. the mock Savanna lesson page
  /media/          runtime media files from the data folder (git-ignored)
  /api/docs        interactive API documentation (generated by FastAPI)
"""

import os
from pathlib import Path

from fastapi import FastAPI
from fastapi.responses import RedirectResponse
from fastapi.staticfiles import StaticFiles

# Folder locations. Inside Docker these are set by the Dockerfile; when running
# from a clone they default to the normal repo layout.
REPO_ROOT = Path(__file__).resolve().parents[2]
EMBED_DIR = Path(os.environ.get("FIDEL_EMBED_DIR", REPO_ROOT / "player" / "dist"))
DEMO_DIR = Path(os.environ.get("FIDEL_DEMO_DIR", REPO_ROOT / "demo"))
DATA_DIR = Path(os.environ.get("FIDEL_DATA_DIR", REPO_ROOT / "data"))

app = FastAPI(
    title="Fidel API",
    version="0.1.0",
    description="Accessible learning media for Ethiopian learning platforms.",
    docs_url="/api/docs",
    openapi_url="/api/openapi.json",
    redoc_url=None,
)


@app.get("/health", tags=["system"])
def health() -> dict:
    """Simple liveness check used by Docker and by tests."""
    return {"status": "ok"}


@app.get("/", include_in_schema=False)
def home() -> RedirectResponse:
    return RedirectResponse(url="/demo/savanna-mock/")


def mount_if_present(url_path: str, folder: Path, name: str) -> None:
    """Serve a folder as static files, if it exists.

    Missing folders are skipped (e.g. the player has not been built yet when
    running unit tests), so the API itself still starts.
    """
    if folder.is_dir():
        app.mount(url_path, StaticFiles(directory=folder, html=True), name=name)


(DATA_DIR / "demo").mkdir(parents=True, exist_ok=True)
mount_if_present("/embed", EMBED_DIR, "embed")
mount_if_present("/demo", DEMO_DIR, "demo")
mount_if_present("/media", DATA_DIR / "demo", "media")
